pub(super) fn classify(sequence: [usize; 4]) -> bool {
    let mut index = 0;
    loop {
        match TREE[index] {
            Node::Leaf(result) => return result,
            Node::Split(feature, threshold, le, gt) => {
                index = if sequence[feature] <= threshold {
                    le
                } else {
                    gt
                };
            }
        }
    }
}
